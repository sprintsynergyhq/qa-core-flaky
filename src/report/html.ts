import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { redactHomeText } from '../report-path.js';
import { VERDICT_ORDER } from '../verdict.js';
import { REPORT_SCRIPT, REPORT_STYLE } from './html-template.js';
import type { TriageEntry, TriageReport, VerdictName } from './schema.js';

const FLAKY_LINE = 'A flaky test can still point to a real app defect. Check the app behavior too.';

const CAUSE_ORDER = ['selectors', 'timing', 'test-data', 'environment', 'unknown'] as const;

const VERDICT_LABEL: Record<VerdictName, string> = {
  'likely-real-bug': 'Likely Real Bug',
  flaky: 'Flaky',
  'broken-test': 'Broken Test',
  'environment-issue': 'Environment Issue',
  'needs-more-runs': 'Needs More Runs',
};

const CAUSE_LABEL: Record<string, string> = {
  selectors: 'Selectors',
  timing: 'Timing',
  'test-data': 'Test Data',
  environment: 'Environment',
  unknown: 'Unknown',
  none: 'None',
};

const CONFIDENCE_LABEL: Record<string, string> = {
  high: 'High',
  medium: 'Medium',
  low: 'Low',
};

const SIGNAL_LABEL: Record<string, string> = {
  'consistent-failure': 'Consistent Failure',
  'same-code-flip': 'Same Code Flip',
  'insufficient-evidence': 'Insufficient Evidence',
  'unexpected-pass': 'Unexpected Pass',
};

const MODE_LABEL: Record<string, string> = {
  repeat: 'Repeat',
  isolated: 'Isolated',
  'in-order': 'In Order',
};

/** How many history marks to draw. The printed count stays exact. */
const HISTORY_MARK_CAP = 24;

export type HtmlRenderOptions = {
  /** Hide home usernames. Default true. Same rules as `parse --redact`. */
  redact?: boolean;
  /** Tool version in the footer. Omit it and the package version is used. */
  version?: string;
};

/**
 * One self-contained HTML page for a triage report.
 * Facts come from the report. Home usernames are hidden unless `redact` is false.
 * The same report and options always produce the same text.
 */
export function renderTriageHtml(report: TriageReport, options: HtmlRenderOptions = {}): string {
  const source = structuredClone(report);
  if (options.redact !== false) redactStrings(source);
  const version = options.version ?? readPackageVersion();
  const styleHash = sourceHash(REPORT_STYLE);
  const scriptHash = sourceHash(REPORT_SCRIPT);
  const policy = [
    "default-src 'none'",
    `script-src '${scriptHash}'`,
    `style-src '${styleHash}'`,
    'img-src data:',
    "font-src 'none'",
    "connect-src 'none'",
    "media-src 'none'",
    "object-src 'none'",
    "frame-src 'none'",
    "worker-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join('; ');

  const body = [
    '<a class="skip" href="#tests">Skip To Tests</a>',
    renderHeader(source),
    '<main>',
    renderSummary(source),
    renderCauses(source),
    renderTests(source),
    '</main>',
    `<footer class="footer">Generated by qa-core-flaky${version ? ` ${escapeHtml(version)}` : ''}</footer>`,
    `<script>${REPORT_SCRIPT}</script>`,
  ].join('');

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<meta name="referrer" content="no-referrer">
<meta http-equiv="Content-Security-Policy" content="${policy}">
<title>Triage Report</title>
<link rel="icon" href="data:,">
<style>${REPORT_STYLE}</style>
</head>
<body>
${body}
</body>
</html>
`;
}

/**
 * Write `triage.html` in `dir`, or leave a previous file in place.
 * The body is written to a temp name and then renamed. A destination that
 * is not a regular file is left as it is.
 */
export function writeTriageHtml(dir: string, html: string): void {
  if (dir.trim() === '') throw new Error('The output directory is empty.');
  const resolved = path.resolve(dir);
  fs.mkdirSync(resolved, { recursive: true });
  const dest = path.join(resolved, 'triage.html');
  if (fs.existsSync(dest) && !fs.statSync(dest).isFile()) {
    throw new Error('triage.html must be a file');
  }
  const tmp = path.join(resolved, `.triage.html.${process.pid}.tmp`);
  try {
    fs.writeFileSync(tmp, html);
    fs.renameSync(tmp, dest);
  } catch (error) {
    fs.rmSync(tmp, { force: true });
    throw error instanceof Error ? error : new Error('unknown error');
  }
}

function renderHeader(report: TriageReport): string {
  const rows: string[] = [];
  if (report.generatedAt) rows.push(metaRow('Generated', report.generatedAt));
  const commits = commitsIn(report);
  if (commits.length > 0) rows.push(metaRow('Commit', commits.join(', ')));
  const branch = extraString(report, 'branch');
  if (branch) rows.push(metaRow('Branch', branch));
  const runId = extraString(report, 'runId');
  if (runId) rows.push(metaRow('Run Id', runId));
  const meta = rows.length > 0 ? `<dl class="meta">${rows.join('')}</dl>` : '';
  return `<header class="top"><div class="top-inner"><p class="mark">qa-core-flaky</p><h1>Triage Report</h1><p class="lede">Failed and flaky tests. Passed tests are not listed.</p>${meta}</div></header>`;
}

function metaRow(label: string, value: string): string {
  return `<div><dt>${escapeHtml(label)}</dt><dd>${escapeHtml(value)}</dd></div>`;
}

function renderSummary(report: TriageReport): string {
  const counts = new Map<VerdictName, number>();
  for (const name of VERDICT_ORDER) counts.set(name, 0);
  for (const entry of report.entries) {
    counts.set(entry.verdict, (counts.get(entry.verdict) ?? 0) + 1);
  }
  const cards = [
    card('Tests Seen', 'tests', report.entries.length),
    ...VERDICT_ORDER.map((name) => card(VERDICT_LABEL[name], name, counts.get(name) ?? 0)),
  ];
  return `<section aria-labelledby="summary-heading"><h2 id="summary-heading">Summary</h2><div class="cards">${cards.join('')}</div></section>`;
}

function card(label: string, key: string, count: number): string {
  return `<article class="card"><p class="card-label">${escapeHtml(label)}</p><p class="card-value" data-summary="${escapeHtml(key)}">${count}</p></article>`;
}

function renderCauses(report: TriageReport): string {
  const counts = causeCounts(report);
  if (report.entries.length === 0) {
    return `<section aria-labelledby="cause-heading"><h2 id="cause-heading">Cause Breakdown</h2><div class="empty"><p class="empty-title">No Causes</p><p>The report has no entries.</p></div></section>`;
  }
  const rows = [...counts.entries()];
  const max = Math.max(1, ...rows.map((row) => row[1] ?? 0));
  const rowH = 32;
  const height = rows.length * rowH;
  const bars = rows.map((row, index) => {
    const cause = row[0] ?? 'unknown';
    const count = row[1] ?? 0;
    const y = index * rowH;
    const width = Math.round((count / max) * 360);
    const name = causeLabel(cause);
    return `<text class="chart-label" x="0" y="${y + 21}">${escapeHtml(name)}</text><rect class="chart-track" x="150" y="${y + 10}" width="360" height="12" rx="2"></rect><rect class="chart-bar" x="150" y="${y + 10}" width="${width}" height="12" rx="2"></rect><text class="chart-count" x="522" y="${y + 21}">${count}</text>`;
  });
  const list = rows
    .map((row) => {
      const cause = row[0] ?? 'unknown';
      const count = row[1] ?? 0;
      return `<li><span>${escapeHtml(causeLabel(cause))}</span> <span data-cause-count="${escapeHtml(cause)}">${count}</span></li>`;
    })
    .join('');
  return `<section aria-labelledby="cause-heading"><h2 id="cause-heading">Cause Breakdown</h2><div class="chart-wrap"><svg class="chart" viewBox="0 0 640 ${height}" width="640" height="${height}" aria-hidden="true">${bars.join('')}</svg></div><ul class="sr-only">${list}</ul></section>`;
}

function renderTests(report: TriageReport): string {
  if (report.entries.length === 0) {
    return `<section id="tests" aria-labelledby="tests-heading"><h2 id="tests-heading">Tests</h2><div class="empty"><p class="empty-title">No Entries</p><p>Every test passed or was skipped. There is nothing to review.</p></div></section>`;
  }
  const head = `<thead><tr>
<th scope="col" data-sort-key="test" aria-sort="none"><button type="button">Test</button></th>
<th scope="col" data-sort-key="verdict" aria-sort="none"><button type="button">Verdict</button></th>
<th scope="col" data-sort-key="cause" aria-sort="none"><button type="button">Cause</button></th>
<th scope="col" data-sort-key="confidence" aria-sort="none"><button type="button">Confidence</button></th>
<th scope="col" data-sort-key="attempts" aria-sort="none"><button type="button">Attempts</button></th>
<th scope="col" data-sort-key="runs" aria-sort="none"><button type="button">Runs Seen</button></th>
</tr></thead>`;
  const bodies = report.entries.map((entry, index) => renderEntry(entry, index)).join('');
  const flaky = report.entries.some((entry) => entry.verdict === 'flaky')
    ? `<p class="caution">${escapeHtml(FLAKY_LINE)}</p>`
    : '';
  return `<section id="tests" aria-labelledby="tests-heading"><h2 id="tests-heading">Tests</h2>${flaky}${renderToolbar(report)}<div class="table-wrap"><table data-report-table><caption class="sr-only">Triage tests</caption>${head}${bodies}</table></div><p id="filter-empty" class="filter-empty" hidden>No Matching Tests</p></section>`;
}

function renderToolbar(report: TriageReport): string {
  const verdicts = VERDICT_ORDER.filter((name) => report.entries.some((entry) => entry.verdict === name));
  const causes = [...causeCounts(report).keys()].filter((cause) => (causeCounts(report).get(cause) ?? 0) > 0);
  const confidences = ['high', 'medium', 'low'].filter((name) =>
    report.entries.some((entry) => entry.confidence === name),
  );
  return `<div class="toolbar">
<div class="field"><label for="filter-verdict">Verdict</label><select id="filter-verdict">${options(verdicts, VERDICT_LABEL)}</select></div>
<div class="field"><label for="filter-cause">Cause</label><select id="filter-cause">${options(causes, CAUSE_LABEL)}</select></div>
<div class="field"><label for="filter-confidence">Confidence</label><select id="filter-confidence">${options(confidences, CONFIDENCE_LABEL)}</select></div>
<div class="field"><label for="filter-search">Search</label><input id="filter-search" type="search" placeholder="Search Tests" autocomplete="off"></div>
<p id="filter-status" class="filter-status" aria-live="polite"></p>
</div>`;
}

function options(values: readonly string[], labels: Record<string, string>): string {
  const parts = ['<option value="">All</option>'];
  for (const value of values) {
    parts.push(`<option value="${escapeHtml(value)}">${escapeHtml(causeLabel(value, labels))}</option>`);
  }
  return parts.join('');
}

function renderEntry(entry: TriageEntry, index: number): string {
  const cause = primaryCause(entry);
  const verdictClass = `badge verdict-${entry.verdict}`;
  return `<tbody data-index="${index}" data-test="${escapeHtml(entry.id)}" data-verdict="${escapeHtml(entry.verdict)}" data-verdict-rank="${verdictRank(entry.verdict)}" data-cause="${escapeHtml(cause)}" data-confidence="${escapeHtml(entry.confidence)}" data-confidence-rank="${confidenceRank(entry.confidence)}" data-failed="${entry.attempts.failed}" data-total="${entry.attempts.total}" data-runs="${entry.history.runsSeen}" data-rule="${escapeHtml(entry.ruleId)}">
<tr>
<th scope="row">${escapeHtml(entry.id)}</th>
<td><span class="${escapeHtml(verdictClass)}">${escapeHtml(verdictLabel(entry.verdict))}</span></td>
<td>${escapeHtml(causeLabel(cause))}</td>
<td>${escapeHtml(confidenceLabel(entry.confidence))}</td>
<td><span class="frac">${entry.attempts.failed}/${entry.attempts.total}</span><span class="sr-only"> failed of ${entry.attempts.total}</span></td>
<td>${entry.history.runsSeen}</td>
</tr>
<tr class="detail-row"><td colspan="6"><details><summary>Show Details</summary>${renderDetail(entry)}</details></td></tr>
</tbody>`;
}

function renderDetail(entry: TriageEntry): string {
  const parts: string[] = ['<div class="detail">'];
  parts.push('<h3>Evidence</h3>');
  if (entry.evidence.length === 0) parts.push('<p>No error text was quoted.</p>');
  else parts.push(`<pre>${entry.evidence.map((line) => escapeHtml(line)).join('\n')}</pre>`);
  parts.push('<h3>Signals</h3>');
  if (entry.signals.length === 0) parts.push('<p>No signal recorded.</p>');
  else {
    parts.push('<ul>');
    for (const signal of entry.signals) {
      parts.push(
        `<li data-signal="${escapeHtml(signal.kind)}"><strong>${escapeHtml(signalLabel(signal.kind))}</strong>: ${escapeHtml(signal.detail)}</li>`,
      );
    }
    parts.push('</ul>');
  }
  parts.push('<h3>Causes</h3>');
  if (entry.causes.length === 0) parts.push('<p>No cause rule matched.</p>');
  else {
    parts.push('<ul>');
    for (const finding of entry.causes) {
      parts.push(
        `<li>${escapeHtml(causeLabel(finding.cause))} (${escapeHtml(confidenceLabel(finding.confidence))}). Rules: ${escapeHtml(finding.ruleIds.join(', '))}</li>`,
      );
    }
    parts.push('</ul>');
  }
  parts.push(`<h3>Suggested Fix</h3><p>${escapeHtml(entry.suggestedFix)}</p>`);
  parts.push(`<h3>Next Step</h3>${renderNextStep(entry.nextStep)}`);
  const reruns = renderReruns(entry);
  if (reruns) parts.push(reruns);
  if (entry.observation) parts.push(`<p>${escapeHtml(entry.observation)}</p>`);
  if (entry.note) parts.push(`<h3>Note</h3><p>${escapeHtml(entry.note)}</p>`);
  if (entry.history.runsSeen > 1) parts.push(renderHistory(entry.history.runsSeen));
  parts.push(
    `<h3>Attempts</h3><p>Total ${entry.attempts.total}, failed ${entry.attempts.failed}, passed ${entry.attempts.passed}. Same code for a pass and a fail: ${entry.attempts.sameCommit ? 'yes' : 'no'}.</p>`,
  );
  parts.push(`<p class="review">Review Status: ${escapeHtml(entry.review.status)}.</p>`);
  parts.push('</div>');
  return parts.join('');
}

function renderNextStep(nextStep: string): string {
  const marker = 'qa-core-flaky rerun ';
  const at = nextStep.indexOf(marker);
  const lead = at === -1 ? nextStep : nextStep.slice(0, at);
  const command = at === -1 ? nextStep : nextStep.slice(at);
  return `<p>${escapeHtml(lead)}</p><p class="command-line"><code>${escapeHtml(command)}</code><button type="button" class="copy">Copy Command</button></p>`;
}

function renderReruns(entry: TriageEntry): string {
  const reruns = entry.attempts.reruns;
  if (!reruns) return '';
  const items: string[] = [];
  for (const mode of ['repeat', 'isolated', 'in-order'] as const) {
    const counts = reruns[mode];
    if (!counts) continue;
    const label = MODE_LABEL[mode] ?? mode;
    if (counts.total > 0) {
      items.push(
        `<li data-rerun="${escapeHtml(mode)}">${escapeHtml(label)}: total ${counts.total}, failed ${counts.failed}, passed ${counts.passed}.</li>`,
      );
    }
    if (counts.notRun) {
      items.push(
        `<li data-rerun="${escapeHtml(mode)}" data-not-run="${counts.notRun}">${escapeHtml(label)} not run ${counts.notRun}: could not select.</li>`,
      );
    }
  }
  if (items.length === 0) return '';
  return `<h3>Reruns</h3><ul>${items.join('')}</ul>`;
}

function renderHistory(runsSeen: number): string {
  const marks = Math.min(runsSeen, HISTORY_MARK_CAP);
  const ticks = Array.from({ length: marks }, () => '<li></li>').join('');
  const cap =
    runsSeen > HISTORY_MARK_CAP
      ? `<p>The strip shows ${HISTORY_MARK_CAP} marks. Runs seen: ${runsSeen}.</p>`
      : '';
  return `<h3>History</h3><p>Runs Seen: ${runsSeen}</p><ol class="strip" aria-hidden="true">${ticks}</ol>${cap}`;
}

function causeCounts(report: TriageReport): Map<string, number> {
  const counts = new Map<string, number>();
  for (const name of CAUSE_ORDER) counts.set(name, 0);
  for (const entry of report.entries) {
    const cause = primaryCause(entry);
    counts.set(cause, (counts.get(cause) ?? 0) + 1);
  }
  return counts;
}

function primaryCause(entry: TriageEntry): string {
  return entry.causes[0]?.cause ?? 'none';
}

function verdictRank(name: string): number {
  const index = VERDICT_ORDER.indexOf(name as VerdictName);
  return index === -1 ? VERDICT_ORDER.length : index;
}

function confidenceRank(name: string): number {
  if (name === 'high') return 0;
  if (name === 'medium') return 1;
  if (name === 'low') return 2;
  return 3;
}

function verdictLabel(name: string): string {
  return VERDICT_LABEL[name as VerdictName] ?? name;
}

function causeLabel(name: string, labels: Record<string, string> = CAUSE_LABEL): string {
  return labels[name] ?? name;
}

function confidenceLabel(name: string): string {
  return CONFIDENCE_LABEL[name] ?? name;
}

function signalLabel(name: string): string {
  return SIGNAL_LABEL[name] ?? name;
}

/**
 * Commit tokens named by signal text, in first-seen order.
 * The sentence is the one the verdict engine writes: "commit <id>".
 */
function commitsIn(report: TriageReport): string[] {
  const seen = new Set<string>();
  const found: string[] = [];
  for (const entry of report.entries) {
    for (const signal of entry.signals) {
      for (const match of signal.detail.matchAll(/\bcommit (\S+)/g)) {
        const raw = match[1];
        if (!raw) continue;
        const token = raw.replace(/[.,;:]+$/g, '');
        if (!token || seen.has(token)) continue;
        seen.add(token);
        found.push(token);
      }
    }
  }
  return found;
}

function extraString(report: TriageReport, key: string): string | undefined {
  const value = (report as unknown as Record<string, unknown>)[key];
  if (typeof value !== 'string') return undefined;
  const trimmed = value.trim();
  return trimmed.length > 0 ? value : undefined;
}

function redactStrings(value: unknown): void {
  if (!value || typeof value !== 'object') return;
  if (Array.isArray(value)) {
    for (let index = 0; index < value.length; index += 1) {
      const item = value[index];
      if (typeof item === 'string') value[index] = redactHomeText(item);
      else redactStrings(item);
    }
    return;
  }
  const record = value as Record<string, unknown>;
  for (const key of Object.keys(record)) {
    const item = record[key];
    if (typeof item === 'string') record[key] = redactHomeText(item);
    else redactStrings(item);
  }
}

function sourceHash(body: string): string {
  return `sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}`;
}

function readPackageVersion(): string {
  const here = path.dirname(fileURLToPath(import.meta.url));
  const pkgPath = path.resolve(here, '../../package.json');
  const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8')) as { version?: string };
  return typeof pkg.version === 'string' ? pkg.version : '';
}

function escapeHtml(value: string): string {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}
